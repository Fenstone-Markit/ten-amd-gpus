            p_ok = mx["cand"] <= THRESHOLDS["P_vs_triton"] * mx["triton"] and mx["cand"] <= THRESHOLDS["P_vs_floor"] * mx["floor"]
            r_ok = mx["cand_self"] == 0
            P_ok &= p_ok; R_ok &= r_ok
            line += f"  cand {mx['cand']:.5f} [{'P ok' if p_ok else 'P FAIL'}]  fp32_ref {mx['fp32_ref']:.5f}  outputs changed over {THRESHOLDS['R_runs']} runs: {int(mx['cand_self'])} [{'R ok' if r_ok else 'R FAIL'}]"
