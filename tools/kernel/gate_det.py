        row = {k: [] for k in KERNELS}; row["hip_self"] = []; row["cand_self"] = []; row["broken"] = []; row["floor"] = []
        for sd in SEEDS:
            c = make_case(K, N, M, sd)
            row["floor"].append(rms_rel(c["ref"].to(torch.bfloat16), c["ref"]))   # the best any bf16 output can do
