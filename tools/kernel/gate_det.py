"""gate_det.py: the frozen gate for the fixed-order (deterministic) variant of gemm_q4_kernel_rdna3. G7 only.

Derived from gate_fp32_v2.py, which passed on the GPU on 2026-09-25. Changes: the candidate is built from
src/q_gemm_rdna3_det.cu; the current fp32 kernel (src/q_gemm_rdna3_fp32_ref.cu, read-only) is built beside it
as fp32_ref; R requires bit-identical output over 20 runs; S also requires cand <= 1.03 x fp32_ref.

DO NOT EDIT THIS FILE. It prints its own md5; the task report must quote it.

  python gate_det.py --preflight   instrument check only (no candidate needed). Must pass before any coding.
  python gate_det.py                full gate on the candidate in src/q_gemm_rdna3_det.cu

Exact reference: random 4-bit weights q, zeros z (true zeros), bf16 scales s and bf16 activations a.
reference = a @ ((q - z) * s), computed in float64. Every kernel is scored as RMS error against it.

Kernels compared:
  triton     production's triton_w4a16_gemm_kernel, as the compiled graph runs it (BLOCK 128/32/32)
  hip_inst   installed gptq_gemm_rdna3 with use_v2_format=True (true zeros), as the patched brain runs it
  cand       the candidate, built from src/q_gemm_rdna3_det.cu with its own namespace
  fp32_ref   the current fp32 kernel (atomics), built from src/q_gemm_rdna3_fp32_ref.cu, for speed comparison

Gates (all numbers fixed in advance, see THRESHOLDS):
  I   instrument: triton and hip_inst near the reference; a wrong-zeros control far from it
  P   precision: cand error <= 1.25 x triton error and <= 1.10 x the bf16 rounding floor, every shape, M = 1 and 4
  R   repeatability: cand output bit-identical across 20 runs, every shape, M = 1 and 4, all seeds
  S   speed: cand per-token total over production's 255 calls <= triton total - 8.0 ms and <= 1.03 x fp32_ref (M = 1 and 4)
  N   identity: cand launches its own kernel and returns bf16 of shape [M, N]
Exit code 0 only if every gate passes.
"""
