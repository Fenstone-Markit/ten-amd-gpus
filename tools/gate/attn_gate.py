"""attn_gate.py: segment count of the Triton 3D decode attention, at the brain's TP8 per-card shapes. G7 only.

DO NOT EDIT THIS FILE. It prints its own md5; every report must quote it.

  python attn_gate.py --preflight   instrument check only (S = 16, 60K, one sequence). Must pass first.
  python attn_gate.py               full sweep and verdict

Runs the INSTALLED vLLM unified_attention and refuses unless its file is byte-identical to the brain's
(md5 b184d334df3d5f88b782e5b92939d6d0, from the running n02-fp32 container). Mirrors production exactly:
blocks of 400 tokens, K and V interleaved per block as kv_cache.unbind(1) gives them, 3 query heads sharing
1 KV head, head size 256, bf16, paged blocks in shuffled order, 3D threshold 128, segment buffers sized
like triton_attn.py (2 x 128 query tokens), k/v descale as expanded ones, softcap 0.

Cases: context 16K, 60K and 100K; x (1 sequence, 1 query token) = decode, (1 sequence, 2 tokens) = the
speculative verify step the brain now runs, (4 sequences, 1 token) = a small concurrent batch.
Segment counts S: 16 (today), 32, 64, 128 (the kernels need a power of two).

Gates, per case and S:
  ran-3D  the attention launch grid is 3-D with S segments (the path under test really ran)
  I       instrument, S = 16 only: error vs an exact float64 reference <= 0.02 RMS relative,
          and a broken control (the block table pointed at decoy blocks with other contents) >= 0.10
Data: random keys and values plus 8 needle keys per sequence that its queries attend to strongly,
spread across the context so they fall in different segments (attention on real text is peaky;
flat random attention would barely exercise how the kernel combines segments).
  P       precision: error(S) <= 1.25 x error(16) + 1e-6
  R       repeatability: two calls bit-identical
Speed, per case and S: 16 layers per token (16 distinct caches, one CUDA graph), median of 20 replays,
events outside the graph.
Recommendation: among S passing ran-3D, P and R on every case, the lowest summed time over the brain's
working cases (60K, 1 sequence, 1 and 2 tokens), provided it is never more than 3 % slower than S = 16 on
any case, and beats S = 16 on the working cases by at least 3 % (otherwise the answer is: keep 16).
Exit 0 only if the instrument passes and a recommendation exists.
"""
